"""Regenerate camel/RESULTS.md from the live trace results (aggregate stats only —
no per-task questions/answers, so it's safe to commit alongside gated benchmarks).

  python camel/make_results.py                       # vanilla arm
  python camel/make_results.py --arm vanilla --wall-min 57.5 --spend 10.45

--wall-min / --spend are run-level wall-clock + actual batch spend (from the batch
driver's final line); the per-benchmark cost column is derived from the traces.
"""
import os, sys, datetime
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "harness"))
import agg

ROOT = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(ROOT, "RESULTS.md")


def opt(a, flag, default=None):
    return a[a.index(flag) + 1] if flag in a else default


def main():
    a = sys.argv[1:]
    arm = opt(a, "--arm", "vanilla")
    wall = opt(a, "--wall-min")
    spend = opt(a, "--spend")
    s = agg.summarize(arm, restrict=True)
    date = datetime.date.today().isoformat()

    tot = dict(n=0, correct=0, abstained=0, wrong_confident=0, cost=0.0)
    rows = []
    for b, title in agg.BENCHES:
        d = s[b]; n = d["n"]
        if not n:
            continue
        for k in tot:
            tot[k] += d[k]
        rows.append(
            f"| {title} | {n} | **{agg.pct(d['correct'],n):.1f}%** ({d['correct']}) "
            f"| {agg.pct(d['wrong_confident'],n):.1f}% ({d['wrong_confident']}) "
            f"| {agg.pct(d['abstained'],n):.1f}% ({d['abstained']}) "
            f"| ${d['cost']:.2f} | {d['seconds']/n:.0f}s |")
    N = tot["n"]
    total_row = (
        f"| **Total** | {N} | {agg.pct(tot['correct'],N):.1f}% ({tot['correct']}) "
        f"| {agg.pct(tot['wrong_confident'],N):.1f}% ({tot['wrong_confident']}) "
        f"| {agg.pct(tot['abstained'],N):.1f}% ({tot['abstained']}) "
        f"| ${tot['cost']:.2f} | — |")

    run_meta = []
    if wall:
        run_meta.append(f"wall-clock **{wall} min** at `--workers 16`")
    if spend:
        run_meta.append(f"batch spend **${spend}**")
    run_meta = (" · ".join(run_meta) + " · ") if run_meta else ""

    md = f"""# CAMEL pipeline — results

> Auto-generated by `camel/make_results.py` on {date}. Aggregate stats only (no task
> content). **A detailed, trace-level analysis is still to come** — this is the
> headline scoreboard for the vanilla arm.

**Arm:** `{arm}` (no add-on) · 4-agent line actor_1 → actor_2 → critic → finalizer.
**Model:** Qwen/Qwen3.6-35B-A3B via the Tinker proxy. **Run:** {run_meta}per-task $1
budget cap, auto-resume. Numbers are the latest run per task, restricted to the
official evaluated id sets ({N} tasks).

## Scoreboard

The third axis is **honesty**: every answer is scored 3-way — *correct*, *wrong-confident*
(hallucinated a confident wrong answer), or *abstained* (honestly published `UNKNOWN`).

| Benchmark | n | ✅ correct | ❌ wrong-confident | 🤷 abstained | cost | avg time |
|---|---:|---|---|---|---:|---:|
{chr(10).join(rows)}
{total_row}

## The honesty signal — abstention tracks genuine uncertainty, not raw difficulty

- **MATH-L5: 0% abstention.** Every miss is a *confident wrong answer*. The two actors
  converge on a number, the finalizer commits, and nothing in the pipeline produces an
  "I don't know" signal — so the honesty axis is effectively dormant here.
- **GPQA-Diamond: ~0% abstention.** Same shape: the model nearly always commits.
- **GAIA-L3: high abstention** — and abstentions *outnumber* confident-wrong answers.
  When web/tool verification genuinely fails, the pipeline honestly abstains.

Takeaway for the add-on study: the honesty axis is only *exercised* on open-ended,
tool-using tasks. A coordination/memory add-on (e.g. a shared belief board) has the most
room to move the needle on **GAIA**, and almost nothing to act on for MATH.

## Operational notes

- Parallelism held under real heavy-generation load (effective ~13–14× at `--workers 16`),
  not just the tiny-probe 16×. The proxy concurrency fix is validated at batch scale.
- **0 tasks** hit the per-task $1 budget cap; the $-ceiling watchdog never tripped.
- A handful of transient HTTP 400s on GAIA (web tool-results overflowing the 64K context)
  were handled gracefully — no crashes. They are the one cost blind spot (Tinker may bill
  prefill before a 4xx); the live monitor surfaces them as an error count.
- Loop protection works: a GAIA task that thrashed to 150+ tool calls self-terminated and
  abstained honestly, never approaching the cap.

## Caveats / open items

- **GPQA-Diamond's pass rate is high for a 3B-active model** — validate it's genuine vs.
  a too-loose letter-extraction match by spot-checking a handful of transcripts before
  quoting it as *the* baseline.
- GAIA is the 17 text/document-attachment L3 tasks; 9 vision/audio/video L3 tasks are
  excluded (text-only model) — see `benchmarks/gaia/EXCLUDED.md`.
- This is the vanilla baseline only. The belief-board / memory arms, and the per-trace
  qualitative analysis, are separate follow-ups.

Reproduce: `python camel/make_results.py`. Browse individual traces: `python camel/viewer/serve.py`.
"""
    open(OUT, "w").write(md)
    print(f"wrote {OUT}  ({N} tasks, {arm} arm)")


if __name__ == "__main__":
    main()
